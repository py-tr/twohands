"""What the Evolus workspace shows for routed cases, computed from our own ledger. No Evolus call, no model call.

    python scripts/evolus_ledger.py           # writes results/evolus/summary.json and results/evolus/summary.md
    python scripts/evolus_ledger.py --check   # the files, docs/EVOLUS.md and the site's Evolus section match the ledger

Input: results/evolus/executions.jsonl (append only, written by `python -m evolus routed`): one "sent" row per
"Audit finding" execution (case id, workflow, execution id, model reported by Evolus, time) and one "returned" row
when the run settles (status, drafted finding, score recomputed by the Evolus Script).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from evolus import routed  # noqa: E402

OUT_J, OUT_M = routed.LEDGER.parent / "summary.json", routed.LEDGER.parent / "summary.md"
DOC = REPO / "docs" / "EVOLUS.md"
TEMPLATE = REPO / "templates" / "results.html"


def compute() -> dict:
    d = routed.summary()
    return {k: v for k, v in d.items()}


def markdown(d: dict) -> str:
    cs = sorted((c for c in routed.cases().values() if c.get("execution_id")), key=lambda c: c.get("started_at") or "")
    L = [f"# Evolus: routed fields as \"{d['workflow']}\" cases, workspace {d['workspace']}", "",
         "Generated by `python scripts/evolus_ledger.py` from `results/evolus/executions.jsonl`; checked by `make eval`.", "",
         d["line"], "",
         "| measure | value |", "|---|---|",
         f"| Executions started (each one AMD call, the AgentCall) | {d['sent']} |",
         f"| Completed with a drafted finding | {d['succeeded']} ({d['success_pct']:g}%) |",
         f"| Failed / still open | {d['failed']} / {d['open']} |",
         f"| Evidence score recomputed in Evolus equals ours | {d['score_agrees']} of {d['succeeded']} |",
         f"| Start errors (HTTP) | {d['http_errors']} |",
         f"| Window (UTC) | {d['window'][0]} to {d['window'][1]} |", "",
         "| case | why the gate routed it | execution | status | finding (excerpt) |", "|---|---|---|---|---|"]
    for c in cs:
        f = " ".join(str(c.get("finding") or "").split())[:160].replace("|", "/")
        L.append(f"| `{c['case_id']}` | {str(c.get('why_routed') or '').replace('|', '/')[:120]} | "
                 f"`{str(c['execution_id'])[:8]}` | {c.get('status')} | {f} |")
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    d = compute()
    if not a.check:
        OUT_J.parent.mkdir(parents=True, exist_ok=True)
        OUT_J.write_text(json.dumps(d, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        OUT_M.write_text(markdown(d), encoding="utf-8")
        print(f"evolus_ledger: wrote {OUT_J.name}, {OUT_M.name}: {d['line']}")
        return 0
    bad = []
    try:
        if json.loads(OUT_J.read_text(encoding="utf-8")) != json.loads(json.dumps(d)):
            bad.append("results/evolus/summary.json differs from the ledger")
        if OUT_M.read_text(encoding="utf-8") != markdown(d):
            bad.append("results/evolus/summary.md differs from the ledger")
    except OSError as e:
        bad.append(str(e))
    doc = " ".join(DOC.read_text(encoding="utf-8").replace("**", "").split())
    if d["line"] not in doc:
        bad.append("docs/EVOLUS.md: missing the current ledger line")
    if "evo.routed.line" not in TEMPLATE.read_text(encoding="utf-8"):
        bad.append("templates/results.html: the Evolus section does not show the ledger line")
    print(f"evolus_ledger --check: {len(bad)} mismatches" + "".join(f"\n  - {b}" for b in bad))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())

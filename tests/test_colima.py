"""Colima, the whole state (PROTOCOL.md Amendment 8b): the Results block, the home card, the blind check of the 13
accepted wrong fields, and the doc lines, all generated by app/colima.py from results/colima/colima_audit.json."""
import json

import pytest
from fastapi.testclient import TestClient

from app import colima, spotcheck
from app.main import app

client = TestClient(app)
pytestmark = pytest.mark.skipif(colima.facts() is None, reason="Colima audit not scored")


def test_doc_lines_and_report_json_match_the_audit():
    assert colima.doc_mismatches() == []
    d = json.loads(colima.AUDIT.read_text(encoding="utf-8"))
    F = colima.facts()
    assert F["read"] == d["read"] and F["prep_rows"] == d["prep_rows"]
    assert F["cert"] + F["ai"] + F["ambiguous"] + F["pending"] == d["disagreements"]
    assert F["pending_on_accepted"] == 0


def test_wording_rules():
    text = " ".join(colima.lines().values()) + colima.who_line(colima.facts())
    low = text.lower()
    for bad in ("fraud", "reviewer", "confirmed by a person", "count was right", "count was wrong"):
        assert bad not in low
    assert "AI adjudicator's reading" in text


def test_results_block_and_home_card():
    r = client.get("/results").text
    L = colima.lines()
    assert 'id="colima"' in r and L["replication"] in r and L["v1"] in r
    assert L["ledger"].replace("'", "&#39;") in r or L["ledger"] in r
    home = client.get("/").text
    assert L["card"] in home and 'href="/results#colima"' in home
    for u in ("/results/colima/report.html", "/results/colima/report.csv", "/results/colima/colima_audit.md"):
        assert client.get(u).status_code == 200, u
    assert client.get("/results/colima/../../.env").status_code == 404


def test_colima13_check_set_is_the_13_and_blind(tmp_path, monkeypatch):
    q = spotcheck.queue("colima13")
    v1 = json.loads(colima.AUDIT.read_text(encoding="utf-8"))["gates"][colima.V1]
    assert sorted(q) == sorted(e.split(" ", 1)[0] for e in v1["errors"])
    assert all(spotcheck._crop_path(k, "colima13").is_file() for k in q)
    page = client.get("/check?set=colima13").text
    v = colima.check13_verdicts()
    for k in q:   # no AI paper value, capture value or model value printed on the blind page
        assert f">{v[k]['paper']}<" not in page
    monkeypatch.setattr(spotcheck, "FILE_C13", tmp_path / "spotcheck_colima13.json")
    assert colima.check13_result() == {"queue": len(q), "answered": 0, "agree": 0}
    for k in q:
        spotcheck.save_answer(k, {"digits": v[k]["paper"], "words": None, "blank": False, "cant_tell": False,
                                  "differ": False}, "colima13")
    p = colima.check13_result()
    assert p == {"queue": len(q), "answered": len(q), "agree": len(q)}
    assert f"checked by a person: {len(q)} of {len(q)} agree" in colima.who_line(colima.facts(), p)

def test_colima13_check_set_is_the_13_and_blind(tmp_path, monkeypatch):
    q = spotcheck.queue("colima13")
    v1 = json.loads(colima.AUDIT.read_text(encoding="utf-8"))["gates"][colima.V1]
    assert sorted(q) == sorted(e.split(" ", 1)[0] for e in v1["errors"])
    assert all(spotcheck._crop_path(k, "colima13").is_file() for k in q)
    page = client.get("/check?set=colima13").text
    v = colima.check13_verdicts()
    for k in q:   # no AI paper value, capture value or model value printed on the blind page
        assert f">{v[k]['paper']}<" not in page
    monkeypatch.setattr(spotcheck, "FILE_C13", tmp_path / "spotcheck_colima13.json")
    assert colima.check13_result() == {"queue": len(q), "answered": 0, "agree": 0}
    for k in q:
        spotcheck.save_answer(k, {"digits": v[k]["paper"], "words": None, "blank": False, "cant_tell": False,
                                  "differ": False}, "colima13")
    p = colima.check13_result()
    assert p == {"queue": len(q), "answered": len(q), "agree": len(q)}
    assert f"checked by a person: {len(q)} of {len(q)} agree" in colima.who_line(colima.facts(), p)


def test_colimarecall_set_is_the_candidates_blind_and_reports_only_when_complete(tmp_path, monkeypatch):
    """PROTOCOL.md Amendment 9: the set is exactly the candidates, the page shows no value, nothing is scored until
    every candidate is answered, then recall = caught / (caught + missed)."""
    C = colima.recall_candidates()
    q = spotcheck.queue("colimarecall")
    assert sorted(q) == sorted(c["item"] for c in C["candidates"]) and len(q) == len(set(q))
    assert all(spotcheck._crop_path(k, "colimarecall").is_file() for k in q)
    assert all(v["paper"] is None and not v["evidence"] for v in spotcheck.load_verdicts("colimarecall").values())
    for c in C["candidates"]:
        assert c["gemma"] == c["capture"] != c["certified"]
    assert all(c["gemma"] == c["certified"] != c["capture"] for c in C["caught"])
    monkeypatch.setattr(spotcheck, "FILE_CR", tmp_path / "spotcheck_colimarecall.json")
    monkeypatch.setattr(colima, "RECALL", tmp_path / "recall.json")   # no scored copy to fall back on: start blank
    page = client.get("/check?set=colimarecall")
    assert page.status_code == 200 and "recall check" in page.text
    R = colima.recall_result()
    assert R["complete"] is False and "recall" not in R and "in progress at /check?set=colimarecall" in colima.recall_line(R)
    by = {c["item"]: c for c in C["candidates"]}
    ans = {}
    for n, k in enumerate(q):   # synthetic answers: one third misses, one third corrections, one third can't tell
        c = by[k]
        ans[k] = ({"digits": c["certified"], "cant_tell": False} if n % 3 == 0 else
                  {"digits": c["capture"], "cant_tell": False} if n % 3 == 1 else {"digits": None, "cant_tell": True})
        if n < len(q) - 1:
            assert colima.recall_result(ans)["complete"] is False
    R = colima.recall_result(ans)
    m, k = len(range(0, len(q), 3)), R["caught"]
    corr = sum(1 for n in range(1, len(q), 3) if by[q[n]]["capture"] is not None)   # a blank capture is not a number
    assert R["complete"] and R["missed"] == m and R["corrections"] == corr
    assert R["ambiguous"] == len(q) - m - R["corrections"] and abs(R["recall"] - k / (k + m)) < 1e-12
    assert R["ci"][0] <= R["recall"] <= R["ci"][1] and R["recall_ambiguous_as_missed"] <= R["recall"]
    assert f"{k} caught, {m} missed" in colima.recall_line(R)


def test_recall_pitch_is_scoped_and_in_every_pitch_text():
    """Amendment 9 as the pitch texts state it: from results/colima/recall.json, scoped (one state, certified-detectable
    errors), never total recall; in the README, slides, EVALUATION and the rendered Results page (lablab.md: the clause and
    the one-sentence Limits line, not the full pitch twice)."""
    R = colima.recall_result()
    p, c = colima.recall_pitch(R), colima.recall_clause(R)
    k, m = R["caught"], R["missed"]
    assert f"{k} of {k + m} caught" in p and "not total recall" in p and "Colima" in p
    assert f"{k} of {k + m}" in c and "not total recall" in c
    lim = colima.recall_limit(R)
    assert f"{k} of {k + m} certified-detectable" in lim and "one state" in lim and "not total recall" in lim
    ch, pr = colima.recall_checked(R), colima.recall_proof(R)
    assert ch == f"recall {k} of {k + m} on the capture errors the certified count reveals (one state, pre-registered)"
    assert pr == f"Recall {k} of {k + m} on certified-detectable errors (pre-registered)"
    assert "recall_checked" in colima.DOCS["README.md"] and "recall_proof" in colima.DOCS["submission/lablab.md"]
    assert colima.recall_checked({"complete": False}) == colima.recall_proof({"complete": False}) == ""
    assert colima.recall_doc_mismatches() == [] and colima.recall_page_mismatches() == []
